# โจทย์ข้อที่ 1: คำนวณราคาสินค้าตามจำนวน
# Input: บรรทัดที่ 1 ราคาสินค้าต่อชิ้น (จำนวนเต็ม)
#        บรรทัดที่ 2 จำนวนชิ้นที่ซื้อ (จำนวนเต็ม)
# เงื่อนไขส่วนลด:
#   - ซื้อตั้งแต่ 10 ชิ้นขึ้นไป ได้ส่วนลด 20%
#   - ซื้อตั้งแต่ 5 ชิ้นขึ้นไป (แต่ไม่ถึง 10 ชิ้น) ได้ส่วนลด 10%
#   - ซื้อน้อยกว่า 5 ชิ้น ไม่ได้ส่วนลด
# Output: ยอดเงินสุทธิที่ต้องจ่าย (แสดงเป็นจำนวนเต็ม)
# ==========================================

# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
m = int(input())
y = int(input())

a = m * y

if y >= 10:
    a *= 0.8  
elif y >= 5:
    a *= 0.9  

print(int(a))
